#!/usr/bin/env node
// Validates data/ and builds feed.js (gitignored). No dependencies.
// GitHub Pages reads data/ directly; feed.js only exists so index.html
// also works opened straight from disk (file:// can't fetch).
//
//   node scripts/build.mjs          build
//   node scripts/build.mjs --check  validate data only, exit 1 on problems

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const BEATS = ['hardware', 'games', 'scene', 'software', 'emulation', 'events', 'press', 'biz'];
const REQUIRED = ['id', 'date', 'beat', 'heat', 'title', 'summary', 'source', 'url'];

const site = JSON.parse(read('data/site.json'));
const threads = JSON.parse(read('data/threads.json'));
const threadIds = new Set(threads.map((t) => t.id));

const problems = [];
const seen = new Set();
const items = read('data/items.jsonl')
  .split('\n')
  .filter((l) => l.trim())
  .map((line, n) => {
    let it;
    try { it = JSON.parse(line); } catch { problems.push(`line ${n + 1}: not JSON`); return null; }
    for (const k of REQUIRED) if (it[k] == null || it[k] === '') problems.push(`${it.id || 'line ' + (n + 1)}: missing ${k}`);
    if (!BEATS.includes(it.beat)) problems.push(`${it.id}: unknown beat "${it.beat}"`);
    if (!(it.heat >= 1 && it.heat <= 5)) problems.push(`${it.id}: heat must be 1-5`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(it.date)) problems.push(`${it.id}: date must be YYYY-MM-DD`);
    if (!/^https?:\/\//.test(it.url || '')) problems.push(`${it.id}: url must be http(s)`);
    if (it.thread && !threadIds.has(it.thread)) problems.push(`${it.id}: unknown thread "${it.thread}"`);
    if ((it.summary || '').split(/\s+/).length > 45) problems.push(`${it.id}: summary over 45 words`);
    if (seen.has(it.id)) problems.push(`${it.id}: duplicate id`);
    seen.add(it.id);
    return it;
  })
  .filter(Boolean)
  .sort((a, b) => b.date.localeCompare(a.date) || b.heat - a.heat);

if (problems.length) {
  console.error('data problems:\n  ' + problems.join('\n  '));
  process.exit(1);
}
if (process.argv.includes('--check')) { console.log(`ok: ${items.length} items, ${threads.length} threads`); process.exit(0); }

const counts = Object.fromEntries(BEATS.map((b) => [b, items.filter((i) => i.beat === b).length]));
const feed = { site, threads, items, counts, built_at: new Date().toISOString() };
writeFileSync(join(root, 'feed.js'), `// generated by scripts/build.mjs — do not edit\nwindow.WATCH_FEED = ${JSON.stringify(feed)};\n`);
console.log(`built feed.js: ${items.length} items, ${threads.length} threads`);
